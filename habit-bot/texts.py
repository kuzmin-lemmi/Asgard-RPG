def build_today_text(
    day: date,
    done: int,
    total: int,
) -> str:
    day_str = day.strftime("%d.%m.%Y")

    if total == 0:
        return (
            "<b>Мои привычки на сегодня</b>\n"
            f"{day_str}\n\n"
            f"{EMPTY_TODAY}"
        )

    return (
        "<b>Мои привычки на сегодня</b>\n"
        f"{day_str}\n\n"
        f"Выполнено: {done} из {total}"
    )

