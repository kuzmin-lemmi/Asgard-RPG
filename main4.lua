while player.isAlive == true and enemy.isAlive == true do
    
    -- 1. ВОСПОЛНЕНИЕ ОД В НАЧАЛЕ ХОДА
    player.actionPoints = 5 
    print("\n========================================")
    print("--- НАЧИНАЕТСЯ ХОД НАСЛЕДНИКА ---")

    -- 2. ЗАПУСК ХОДА ИГРОКА (ВНУТРЕННИЙ ЦИКЛ)
    while player.actionPoints > 0 do
        
        -- Показываем актуальное состояние
        print("Здоровье Героя: " .. player.health .. " | Здоровье Врага: " .. enemy.health)
        print("Ваши Очки Действий (ОД): " .. player.actionPoints)
        print("\nЧТО ДЕЛАЕМ?")
        print("[1] Атаковать Ржавого Дрона (Стоит 2 ОД)")
        print("[9] Закончить ход") -- Новая опция

        io.write("\nВаш выбор: ")
        choice = io.read() 

        if choice == "1" then
            -- 3. ПРОВЕРКА РЕСУРСОВ (Хватает ли ОД?)
            if player.actionPoints >= 2 then
                -- Хватает! Выполняем действие.
                
                -- А. Тратим ОД
                player.actionPoints = player.actionPoints - 2
                
                -- Б. Рассчитываем урон (пока просто)
                damage = player.strength
                
                -- В. Наносим урон врагу
                enemy.health = enemy.health - damage
                
                print("\n>>> АТАКА! Вы нанесли " .. damage .. " урона!")
                print("У Дрона осталось " .. enemy.health .. " здоровья.")
                print("У вас осталось " .. player.actionPoints .. " ОД.")
            
            else
                -- Не хватает ОД!
                print("\n>>> НЕДОСТАТОЧНО ОД ДЛЯ АТАКИ!")
            end
        
        elseif choice == "9" then
            -- 4. ИСПОЛЬЗУЕМ "РУНУ РАЗРЫВА"
            print("\n>>> ВЫБОР: ЗАКОНЧИТЬ ХОД!")
            print("Вы готовитесь к атаке противника...")
            player.actionPoints = 0 -- Обнуляем ОД, чтобы цикл завершился
            break -- "Ломаем" ВНУТРЕННИЙ цикл (Ход Игрока)
        
        else
            print("\n>>> НЕИЗВЕСТНАЯ КОМАНДА! Вы теряете 1 ОД.")
            player.actionPoints = player.actionPoints - 1
        end

        -- 5. Проверка, не закончились ли ОД
        if player.actionPoints <= 0 then
             print("\n...Очки Действий иссякли...")
        end

    end -- Конец ВНУТРЕННЕГО цикла (Ход Игрока)

    -- 6. ЗАГЛУШКА ДЛЯ ХОДА ВРАГА
    print("\n--- ХОД ИГРОКА ЗАВЕРШЕН ---")
